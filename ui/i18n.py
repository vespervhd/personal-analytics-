def current_lang() -> str:
    """Return the active language code (``"fa"`` by default)."""
    try:
        lang = st.session_state.get("lang", "fa")
    except Exception:
        return "fa"
    return lang if lang in STRINGS else "fa"


def t(key: str, lang: str | None = None) -> str:
    """Return the string for ``key`` in the active language.

    Falls back to English, then to the key itself. ``lang`` overrides
    the session language (used by tests, which run outside a session).
    """
    code = lang if lang in STRINGS else current_lang()
    table = STRINGS.get(code, {})
    if key in table:
        return table[key]
    if key in STRINGS["en"]:
        return STRINGS["en"][key]
    return key


def rtl_style(lang: str | None = None) -> str:
    """Return the RTL + Vazirmatn injection for Persian, else ``""``.

    For English this returns an empty string so the default LTR layout
    is untouched. The returned HTML links the Vazirmatn font and sets
    ``direction: rtl`` on the app container and the sidebar.
    """
    code = lang if lang in STRINGS else current_lang()
    if code != "fa":
        return ""
    return (
        f'<link href="{FONT_URL}" rel="stylesheet">\n'
        "<style>\n"
        "html, body, [data-testid=\"stAppViewContainer\"], "
        "[data-testid=\"stSidebar\"] {\n"
        "  direction: rtl;\n"
        "  font-family: 'Vazirmatn', Tahoma, sans-serif;\n"
        "}\n"
        "[data-testid=\"stSidebar\"] *, .stApp input, .stApp textarea, "
        ".stApp select {\n"
        "  font-family: 'Vazirmatn', Tahoma, sans-serif;\n"
        "}\n"
        "</style>"
    )
